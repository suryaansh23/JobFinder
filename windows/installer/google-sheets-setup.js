#!/usr/bin/env node
/* eslint-disable no-console */
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const readline = require('node:readline/promises');

const SCOPE = 'https://www.googleapis.com/auth/spreadsheets';
const TOKEN_URL = 'https://oauth2.googleapis.com/token';
const AUTH_URL = 'https://accounts.google.com/o/oauth2/v2/auth';

function parseSpreadsheetId(input) {
  const s = String(input || '').trim();
  const m = s.match(/\/spreadsheets\/d\/([A-Za-z0-9_-]+)/);
  if (m) return m[1];
  if (/^[A-Za-z0-9_-]{20,}$/.test(s)) return s;
  return '';
}

function envFilePath() {
  if (!process.env.APPDATA) throw new Error('APPDATA is not available.');
  return path.join(process.env.APPDATA, 'JobFinder', 'JobFinder.env.cmd');
}

function writeEnv({ spreadsheetId, clientId, clientSecret, refreshToken }) {
  const file = envFilePath();
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const lines = [
    '@echo off',
    'REM Generated by JobFinder Google Sheets setup. Keep this file private.',
    `set "JOBFINDER_TRACKER_SPREADSHEET_ID=${spreadsheetId}"`,
    'set "JOBFINDER_TRACKER_TAB=Automation Queue"',
    'set "JOBFINDER_INTERVENTION_TAB=Interventions"',
    `set "GOOGLE_CLIENT_ID=${clientId}"`,
    `set "GOOGLE_CLIENT_SECRET=${clientSecret}"`,
    `set "GOOGLE_REFRESH_TOKEN=${refreshToken}"`,
    '',
  ];
  fs.writeFileSync(file, lines.join('\r\n'), { encoding: 'utf8', mode: 0o600 });
  return file;
}

async function waitForOAuthCode(redirectPath = '/oauth2callback') {
  let resolveCode;
  let rejectCode;
  const codePromise = new Promise((resolve, reject) => {
    resolveCode = resolve;
    rejectCode = reject;
  });

  const server = http.createServer((req, res) => {
    try {
      const u = new URL(req.url, 'http://127.0.0.1');
      if (u.pathname !== redirectPath) {
        res.writeHead(404, { 'content-type': 'text/plain' });
        res.end('Not found');
        return;
      }
      const err = u.searchParams.get('error');
      const code = u.searchParams.get('code');
      if (err) {
        res.writeHead(400, { 'content-type': 'text/html; charset=utf-8' });
        res.end('<h2>JobFinder Google authorization was cancelled.</h2><p>You can close this tab.</p>');
        rejectCode(new Error(`Google authorization failed: ${err}`));
        return;
      }
      if (!code) {
        res.writeHead(400, { 'content-type': 'text/plain' });
        res.end('Missing authorization code.');
        rejectCode(new Error('Google did not return an authorization code.'));
        return;
      }
      res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
      res.end('<h2>Google Sheets connected to JobFinder.</h2><p>You can close this tab and return to the setup window.</p>');
      resolveCode(code);
    } catch (e) {
      rejectCode(e);
    }
  });

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });

  const port = server.address().port;
  const redirectUri = `http://127.0.0.1:${port}${redirectPath}`;
  return { server, codePromise, redirectUri };
}

async function exchangeCode({ code, clientId, clientSecret, redirectUri }) {
  const body = new URLSearchParams({
    code,
    client_id: clientId,
    client_secret: clientSecret,
    redirect_uri: redirectUri,
    grant_type: 'authorization_code',
  });
  const r = await fetch(TOKEN_URL, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body,
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.error_description || j.error || `Token exchange failed (HTTP ${r.status})`);
  if (!j.access_token) throw new Error('Google did not return an access token.');
  if (!j.refresh_token) {
    throw new Error('Google did not return a refresh token. Re-run setup and approve access when prompted.');
  }
  return j;
}

async function validateTracker(spreadsheetId, accessToken) {
  const headers = {
    queue: ['record_id','job_id','queued_at','company','role','location','source','url','priority','status','apply_channel','cv','confirmation','application_reference','applied_at','action_required','action_reason','last_attempt_at','attempts','notes'],
    interventions: ['intervention_id','profile_id','field_key','job_id','company','role','question','type','options','answer','status','asked_at','resolved_at'],
  };

  async function read(range) {
    const encoded = encodeURIComponent(range);
    const r = await fetch(`https://sheets.googleapis.com/v4/spreadsheets/${encodeURIComponent(spreadsheetId)}/values/${encoded}?majorDimension=ROWS`, {
      headers: { authorization: `Bearer ${accessToken}` },
    });
    const j = await r.json().catch(() => ({}));
    if (!r.ok) throw new Error(j?.error?.message || `Sheets validation failed (HTTP ${r.status})`);
    return j.values?.[0] || [];
  }

  const q = await read("'Automation Queue'!A1:T1");
  const i = await read("'Interventions'!A1:M1");

  const qOk = headers.queue.every((h, idx) => String(q[idx] || '').trim() === h);
  const iOk = headers.interventions.every((h, idx) => String(i[idx] || '').trim() === h);
  if (!qOk || !iOk) {
    throw new Error('Tracker tabs exist, but their headers do not match the JobFinder template.');
  }
}

function openBrowser(url) {
  try {
    const child = spawn('rundll32.exe', ['url.dll,FileProtocolHandler', url], {
      detached: true,
      stdio: 'ignore',
      windowsHide: true,
    });
    child.unref();
    return true;
  } catch {
    return false;
  }
}

async function main() {
  if (process.argv.includes('--self-test')) {
    const cases = [
      ['https://docs.google.com/spreadsheets/d/abcDEF_12345678901234567890/edit', 'abcDEF_12345678901234567890'],
      ['abcDEF_12345678901234567890', 'abcDEF_12345678901234567890'],
      ['not-a-sheet', ''],
    ];
    for (const [input, expected] of cases) {
      const got = parseSpreadsheetId(input);
      if (got !== expected) throw new Error(`parseSpreadsheetId failed for ${input}: ${got}`);
    }
    console.log('Google Sheets setup helper self-test passed.');
    return;
  }

  if (process.platform !== 'win32') {
    throw new Error('This setup helper is intended for the packaged Windows build.');
  }

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log('');
  console.log('===========================================================');
  console.log(' JobFinder - Connect Google Sheets');
  console.log('===========================================================');
  console.log('');
  console.log('You need a Google OAuth Desktop App client ID and client secret.');
  console.log('The browser sign-in and refresh token are handled automatically by this helper.');
  console.log('');

  const sheetInput = await rl.question('Paste the JobFinder Master Tracker URL or spreadsheet ID: ');
  const spreadsheetId = parseSpreadsheetId(sheetInput);
  if (!spreadsheetId) throw new Error('That does not look like a Google Sheets URL or spreadsheet ID.');

  const clientId = (await rl.question('Google OAuth client ID: ')).trim();
  const clientSecret = (await rl.question('Google OAuth client secret: ')).trim();
  if (!clientId || !clientSecret) throw new Error('Client ID and client secret are required.');

  const { server, codePromise, redirectUri } = await waitForOAuthCode();
  try {
    const auth = new URL(AUTH_URL);
    auth.searchParams.set('client_id', clientId);
    auth.searchParams.set('redirect_uri', redirectUri);
    auth.searchParams.set('response_type', 'code');
    auth.searchParams.set('scope', SCOPE);
    auth.searchParams.set('access_type', 'offline');
    auth.searchParams.set('prompt', 'consent');
    auth.searchParams.set('include_granted_scopes', 'true');

    console.log('');
    console.log('Opening Google authorization in your browser...');
    if (!openBrowser(auth.toString())) {
      console.log('Open this URL manually:');
      console.log(auth.toString());
    }

    const code = await Promise.race([
      codePromise,
      new Promise((_, reject) => setTimeout(() => reject(new Error('Authorization timed out after 5 minutes.')), 5 * 60 * 1000)),
    ]);

    console.log('Authorization received. Validating tracker...');
    const tokens = await exchangeCode({ code, clientId, clientSecret, redirectUri });
    await validateTracker(spreadsheetId, tokens.access_token);

    const file = writeEnv({
      spreadsheetId,
      clientId,
      clientSecret,
      refreshToken: tokens.refresh_token,
    });

    console.log('');
    console.log('Google Sheets connection verified.');
    console.log(`Configuration saved to: ${file}`);
    console.log('JobFinder will use Automation Queue and Interventions from this spreadsheet.');
    console.log('');
    console.log('If JobFinder is already running, the watchdog will reload this configuration on its next restart.');
  } finally {
    rl.close();
    server.close();
  }
}

main().catch((e) => {
  console.error('');
  console.error('[X] Google Sheets setup failed:');
  console.error('    ' + String(e?.message || e));
  process.exit(1);
});
